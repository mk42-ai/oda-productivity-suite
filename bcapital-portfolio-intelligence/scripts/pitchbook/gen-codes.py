#!/usr/bin/env python3
"""Generate src/pitchbook/codes.ts from the PitchBook lookup-tables JSON.

Usage: python3 scripts/pitchbook/gen-codes.py [path/to/15-getLookupTables.json]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else "/tmp/wt10/pbin/15-getLookupTables.json"
OUT = os.path.join(ROOT, "src", "pitchbook", "codes.ts")

TABLES = ["DEAL_TYPE", "INDUSTRY", "VERTICAL", "COUNTRY", "REGION", "OWNERSHIP_STATUS", "BUSINESS_STATUS"]

# Hand-maintained extras (not in the lookup file, but in the field inventory).
INVESTOR_TYPE = {
    "VC": "Venture Capital", "ANI": "Angel (individual)", "SWF": "Sovereign Wealth Fund",
    "PEBO": "PE/Buyout", "GWTHEX": "Growth/Expansion", "ACINC": "Accelerator/Incubator",
    "CVC": "Corporate Venture Capital", "COR": "Corporation", "HF": "Hedge Fund",
    "FOF": "Fund of Funds", "FAM": "Family Office", "UNIV": "University", "GOV": "Government",
    "AM": "Asset Manager", "IB": "Investment Bank", "OTH": "Other",
}
INVESTOR_STATUS = {"ACT": "Active Investor", "WO": "Former Investor"}


def find_items(o):
    if isinstance(o, dict):
        it = o.get("items")
        if isinstance(it, list) and it and isinstance(it[0], dict) and "tableName" in it[0]:
            return it
        for v in o.values():
            r = find_items(v)
            if r:
                return r
    if isinstance(o, list):
        for v in o:
            r = find_items(v)
            if r:
                return r
    return None


def ts_str(s):
    return json.dumps(str(s), ensure_ascii=False)


def emit_table(name, mapping):
    lines = [f"  {name}: {{"]
    for code, desc in mapping.items():
        lines.append(f"    {ts_str(code)}: {ts_str(desc)},")
    lines.append("  },")
    return "\n".join(lines)


def main():
    with open(SRC, encoding="utf-8") as f:
        items = find_items(json.load(f))
    if not items:
        sys.exit("no lookup items found in " + SRC)
    tables = {}
    for it in items:
        tn = it.get("tableName")
        if tn not in TABLES:
            continue
        m = {}
        for c in it.get("codes") or []:
            code = c.get("code")
            if code is None:
                continue
            m[str(code)] = str(c.get("description") or "")
        tables[tn] = m
    missing = [t for t in TABLES if t not in tables]
    if missing:
        sys.exit("missing tables: " + ", ".join(missing))

    counts = ", ".join(f"{t} {len(tables[t])}" for t in TABLES)
    body = [
        "// AUTO-GENERATED by scripts/pitchbook/gen-codes.py — do not edit by hand.",
        f"// Source: {os.path.basename(SRC)} ({counts}).",
        "// INDUSTRY codes are hierarchical: 2-char sector, 4-char group, 6-char sub-industry (parent = first 4 chars).",
        "",
        'export type PbLookupTable = "DEAL_TYPE" | "INDUSTRY" | "VERTICAL" | "COUNTRY" | "REGION" | "OWNERSHIP_STATUS" | "BUSINESS_STATUS";',
        'export type PbExtraTable = "INVESTOR_TYPE" | "INVESTOR_STATUS";',
        "export type PbCodeTable = PbLookupTable | PbExtraTable;",
        "",
        "export const CODES: Record<PbLookupTable, Record<string, string>> = {",
    ]
    for t in TABLES:
        body.append(emit_table(t, tables[t]))
    body.append("};")
    body.append("")
    body.append("/** Hand-maintained: investor type codes (from the brief / field inventory, not in the lookup file). */")
    body.append("export const INVESTOR_TYPE: Record<string, string> = {")
    for k, v in INVESTOR_TYPE.items():
        body.append(f"  {ts_str(k)}: {ts_str(v)},")
    body.append("};")
    body.append("")
    body.append("/** Hand-maintained: investor status codes. */")
    body.append("export const INVESTOR_STATUS: Record<string, string> = {")
    for k, v in INVESTOR_STATUS.items():
        body.append(f"  {ts_str(k)}: {ts_str(v)},")
    body.append("};")
    body.append("")
    body.append("export const ALL_CODES: Record<PbCodeTable, Record<string, string>> = { ...CODES, INVESTOR_TYPE, INVESTOR_STATUS };")
    body.append("")
    body.append("/** Parent INDUSTRY code (first 4 chars) for a 6-char sub-industry code, else null. */")
    body.append("export function industryParent(code: string): string | null {")
    body.append("  const c = String(code);")
    body.append("  if (c.length === 6) return c.slice(0, 4);")
    body.append("  if (c.length === 4) return c.slice(0, 2);")
    body.append("  return null;")
    body.append("}")
    body.append("")
    body.append("/**")
    body.append(" * Decode a code to its description. Never returns null: unknown codes are returned verbatim")
    body.append(" * and a warning is pushed onto `warnings` (if given).")
    body.append(" */")
    body.append("export function decodeCode(table: PbCodeTable, code: string | number | null | undefined, warnings?: string[]): string {")
    body.append('  if (code === null || code === undefined || code === "") return "";')
    body.append("  const key = String(code);")
    body.append("  const hit = ALL_CODES[table]?.[key];")
    body.append("  if (hit !== undefined) return hit;")
    body.append("  if (warnings) warnings.push(`unknown ${table} code: ${key}`);")
    body.append("  return key;")
    body.append("}")
    body.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(body))
    print(f"wrote {OUT}: {counts}; INVESTOR_TYPE {len(INVESTOR_TYPE)}, INVESTOR_STATUS {len(INVESTOR_STATUS)}")


if __name__ == "__main__":
    main()
