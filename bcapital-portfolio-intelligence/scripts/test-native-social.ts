import assert from "node:assert/strict";
import fs from "node:fs";
import { matchNativeRelevance, readNativePosts, nativeStorageStatus, readCollectionState } from "../src/social-native.js";
const companies = JSON.parse(fs.readFileSync("data/portfolio.json", "utf8")).companies;
assert.equal(matchNativeRelevance("95 percent culprits handled", companies), null);
assert.equal(matchNativeRelevance("@someone Hello!", companies), null);
assert.equal(matchNativeRelevance("Sonilo raised an investment round", companies)?.company_slug, "sonilo");
const posts = await readNativePosts();
assert.ok(posts.length >= 2);
assert.equal(new Set(posts.map((p) => p.id)).size, posts.length);
assert.equal(new Set(posts.map((p) => p.url)).size, posts.length);
assert.ok(posts.every((p) => p.provenance.kind === "provider-response"));
assert.ok(posts.some((p) => p.company_slug === "sonilo"));
assert.ok(!posts.some((p) => /katsukeno/i.test(p.author_handle || "")));
assert.ok(posts.every((p) => p.retrieved_at === null && !!p.first_seen_at));
const state = await readCollectionState();
assert.equal(state.workers.length, 50);
assert.equal(new Set(state.workers.map((w: any) => w.label)).size, 50);
assert.ok(state.workers.every((w: any) => w.status === "not_launched" && w.platform_worker_id === null && w.session_id === null));
assert.equal(state.batch_http_status, 405);
assert.equal(typeof nativeStorageStatus().durable_configured, "boolean");
console.log(JSON.stringify({ native_posts: posts.length, workers_reserved: 50, workers_launched: 0, durable_remote: false, status: "passed" }));
